#!/usr/bin/env python3
"""Night look = Paper turned dark (Chu 11/26). Generates the Night CSS from the Paper CSS, so every Paper rule
has a Night twin and the two can never drift apart.

  site/style.css        -> site/night.css         (home + track pages; linked right after style.css)

Each `html.paper …` rule is copied with `html.paper.night …` as the selector (one class stronger, so it wins) and its
colours swapped with the table below: cream paper -> warm charcoal, dark ink -> warm cream, gold/greens/blues lifted so
they still read on a dark ground. Safety colours (SOS red, purple, neon green line) keep their meaning.
Run after editing either Paper file:  python3 tools/night.py   (build.py runs it too)
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = os.path.join(ROOT, "site")

# Paper colour -> Night colour.  Ink and paper swap places; everything else is lifted for a dark ground.
SWAP = {
    "#f3eee3": "#121110",  # page ground
    "#fbf8f1": "#1b1916",  # cards, bars, buttons (paper)
    "#efe8da": "#24211c",  # second card / map ground
    "#f6f0e3": "#221f1a",  # card hover
    "#f1ebdd": "#221f1a",
    "#e9e1cf": "#2a2620",  # my row
    "#e5dccb": "#2e2a23",  # progress bars
    "#e2d9c7": "#2e2a23",  # row lines
    "#d9cfbb": "#38332b",  # lines
    "#cfc4ad": "#4a4338",  # button edges
    "#c9bea6": "#4a4338",
    "#16140f": "#ece4d4",  # ink
    "#2a261d": "#d8cfbd",  # ink hover
    "#4a443a": "#cbc2b1",
    "#5e574a": "#a99f8c",  # muted ink
    "#6b6356": "#968c7a",
    "#8a5a00": "#e3ab4d",  # gold
    "#fbf3dc": "#2a2213",  # "read first" box
    "#d8b864": "#6e5722",
    "#5a3d00": "#ebc97c",
    "#1e9e4a": "#35c46b",  # L1 green
    "#1446c8": "#5b8dff",  # L2 blue
    "#d96c00": "#ff9a2e",  # double track orange
    "#c62828": "#e53935",  # red (still white text on it)
    "#d32f2f": "#ef4b47",
    "#b45309": "#f08a3c",
}
# rgba() with paper or ink inside
RGBA = [
    (r"rgba\(\s*251\s*,\s*248\s*,\s*241\s*,", "rgba(27,25,22,"),    # paper with see-through
    (r"rgba\(\s*243\s*,\s*238\s*,\s*227\s*,", "rgba(18,17,16,"),
    (r"rgba\(\s*22\s*,\s*20\s*,\s*15\s*,", "rgba(236,228,212,"),    # ink with see-through
]
SHADOW = re.compile(r"rgba\(\s*(40\s*,\s*30\s*,\s*15|60\s*,\s*45\s*,\s*20)\s*,\s*([.\d]+)\s*\)")

# Night map = dark map (invert + hue-rotate on the tiles only, route lines untouched). Chu picked it 11/26 over a dimmed map
# ("grayscale(.65) sepia(.25) brightness(.52) contrast(1.12)"), which looked muddy grey.
MAP_FILTER = "invert(1) hue-rotate(180deg) grayscale(.55) sepia(.2) brightness(.92) contrast(.92)"


def night_value(prop, val):
    def hexsub(m):
        h = m.group(0).lower()
        if h in ("#fff", "#ffffff"):
            return h if prop == "color" or prop.startswith("border") else "#2a2620"  # white text stays white; white boxes go dark
        return SWAP.get(h, m.group(0))
    val = re.sub(r"#[0-9a-fA-F]{3,8}\b", hexsub, val)
    for pat, rep in RGBA:
        val = re.sub(pat, rep, val)
    val = SHADOW.sub(lambda m: f"rgba(0,0,0,{min(0.75, float(m.group(2)) * 1.8):.2f})", val)
    val = val.replace("color-scheme: light", "color-scheme: dark")
    return val


def night_block(body):
    out = []
    for decl in body.split(";"):
        if ":" not in decl:
            if decl.strip():
                out.append(decl)
            continue
        prop, val = decl.split(":", 1)
        p = prop.strip().lower()
        if p == "color-scheme":
            out.append(f"{prop}: dark")
            continue
        out.append(f"{prop}:{night_value(p, val)}")
    return ";".join(out)


def split_top(sel):
    """Split a selector list on its top-level commas only: ':is(h1, h2)' stays whole (a plain split broke night.css 11/26)."""
    out, depth, cur = [], 0, ""
    for ch in sel:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur); cur = ""
        else:
            cur += ch
    out.append(cur)
    return out


def convert(src_name, out_name, extra=""):
    s = open(os.path.join(SITE, src_name), encoding="utf-8").read()
    s = re.sub(r"/\*.*?\*/", "", s, flags=re.S)
    rules = []
    for sel, body in re.findall(r"([^{}]+)\{([^{}]*)\}", s):
        sels = [x.strip() for x in split_top(sel)]
        if not any("html.paper" in x or "html:root.paper" in x for x in sels):
            continue
        keep = [x.replace("html:root.paper", "html:root.paper.night").replace("html.paper", "html.paper.night")
                for x in sels if "paper" in x]
        nb = night_block(body)
        if re.sub(r"\s+", "", nb) == re.sub(r"\s+", "", body):
            continue  # nothing to change at night
        rules.append(",\n".join(keep) + " {" + nb + "}")
    head = f"/* GENERATED by tools/night.py from {src_name} — do not edit by hand. Night look = Paper turned dark. */\n"
    open(os.path.join(SITE, out_name), "w", encoding="utf-8").write(head + "\n".join(rules) + "\n" + extra)
    return len(rules)


